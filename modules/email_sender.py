"""
email_sender.py
===============
RPA Module: Email Sender
Sends (or mocks) welcome emails to new employees.

EmailMode (from Config.xlsx):
  "mock"  → prints email to console & saves to Logs/MockEmails/
  "smtp"  → actually sends via SMTP (requires SenderEmail + SenderPassword in config)
"""

