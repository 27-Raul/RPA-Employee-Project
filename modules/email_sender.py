def send_welcome_email(employee_data: dict, config: dict,
                        attachment_path: str = None) -> dict:
    """
    Sends (or mocks) a welcome email to the new employee.

    Args:
        employee_data: Dict with employee fields + employee_id
        config: Dict from Config.xlsx (read via excel_handler.read_config)
        attachment_path: Optional path to the welcome letter PDF to attach

    Returns:
        {"success": True/False, "mode": "mock"/"smtp", "error": "..."}
    """
    email_mode   = config.get("EmailMode", "mock").lower()
    company_name = config.get("CompanyName", "ABC Technologies")
    emp_id       = employee_data.get("employee_id", "N/A")
    to_email     = employee_data.get("email", "")
    full_name    = employee_data.get("full_name", "Employee")

    subject = config.get("EmailSubject", "Welcome to {CompanyName} - {EmployeeID}")
    subject = subject.replace("{CompanyName}", company_name).replace("{EmployeeID}", emp_id)

    body_text = build_email_body(employee_data, company_name)
    body_html = build_email_html(employee_data, company_name)

    # ── Mock Mode ──────────────────────────────────────────────────────────────
    if email_mode == "mock":
        try:
            mock_dir = os.path.join("Logs", "MockEmails")
            os.makedirs(mock_dir, exist_ok=True)
            timestamp = datetime.now().strftime("%Y%m%d_%H%M%S")
            mock_file = os.path.join(mock_dir, f"Email_{emp_id}_{timestamp}.txt")

            with open(mock_file, "w", encoding="utf-8") as f:
                f.write(f"TO      : {to_email}\n")
                f.write(f"FROM    : HR Department <{config.get('SenderEmail', 'hr@abc.com')}>\n")
                f.write(f"SUBJECT : {subject}\n")
                f.write(f"DATE    : {datetime.now().strftime('%Y-%m-%d %H:%M:%S')}\n")
                f.write(f"ATTACH  : {attachment_path or 'None'}\n")
                f.write("─" * 60 + "\n")
                f.write(body_text)

            logger.info(f"[MOCK EMAIL] Saved to {mock_file}")
            print(f"\n{'='*60}")
            print(f"  📧 MOCK EMAIL — {emp_id} ({full_name})")
            print(f"{'='*60}")
            print(f"  TO:      {to_email}")
            print(f"  SUBJECT: {subject}")
            print(f"  MODE:    Mock (no real email sent)")
            print(f"  SAVED:   {mock_file}")
            print(f"{'='*60}\n")

            return {"success": True, "mode": "mock", "error": None, "saved_path": mock_file}
        except Exception as e:
            msg = f"Failed to save mock email for {emp_id}: {e}"
            logger.error(msg)
            return {"success": False, "mode": "mock", "error": msg}

    # ── SMTP Mode ──────────────────────────────────────────────────────────────
    elif email_mode == "smtp":
        try:
            import smtplib
            from email.mime.multipart import MIMEMultipart
            from email.mime.text import MIMEText
            from email.mime.base import MIMEBase
            from email import encoders

            smtp_server   = config.get("SMTPServer", "smtp.gmail.com")
            smtp_port     = int(config.get("SMTPPort", 587))
            sender_email  = config.get("SenderEmail", "")
            sender_pass   = config.get("SenderPassword", "")

            if not sender_email or not sender_pass:
                raise ValueError("SenderEmail and SenderPassword must be set in Config.xlsx for SMTP mode.")

            msg = MIMEMultipart("alternative")
            msg["Subject"] = subject
            msg["From"]    = f"HR Department <{sender_email}>"
            msg["To"]      = to_email

            msg.attach(MIMEText(body_text, "plain"))
            msg.attach(MIMEText(body_html, "html"))

            # Attach PDF if provided
            if attachment_path and os.path.exists(attachment_path):
                with open(attachment_path, "rb") as f:
                    part = MIMEBase("application", "octet-stream")
                    part.set_payload(f.read())
                encoders.encode_base64(part)
                part.add_header(
                    "Content-Disposition",
                    f"attachment; filename={os.path.basename(attachment_path)}"
                )
                msg.attach(part)

            with smtplib.SMTP(smtp_server, smtp_port) as server:
                server.ehlo()
                server.starttls()
                server.login(sender_email, sender_pass)
                server.sendmail(sender_email, to_email, msg.as_string())

            logger.info(f"Welcome email sent via SMTP to {to_email} for {emp_id}")
            return {"success": True, "mode": "smtp", "error": None}

        except Exception as e:
            msg = f"SMTP email failed for {emp_id}: {e}"
            logger.error(msg)
            return {"success": False, "mode": "smtp", "error": msg}

    else:
        msg = f"Unknown EmailMode '{email_mode}'. Use 'mock' or 'smtp'."
        logger.error(msg)
        return {"success": False, "mode": email_mode, "error": msg}
