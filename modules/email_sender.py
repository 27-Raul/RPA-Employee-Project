import logging
from datetime import datetime

logger = logging.getLogger("RPA_Onboarding")


def _format_date(date_str: str) -> str:
    try:
        from datetime import datetime as dt
        return dt.strptime(date_str, "%Y-%m-%d").strftime("%d %B %Y")
    except Exception:
        return date_str


